import assert from "node:assert/strict";
import { buildAssetDisposal, summarizeAssetDisposals, validateAssetDisposal } from "../js/asset-disposals-core.js";
const asset = { client_uid: "asset-1", name: "Véhicule", account: "2455", amount: 12000, date: "2022-01-01", amortized: 8000 };
const sale = buildAssetDisposal(asset, { date: "2026-11-25", type: "cession", proceeds: 6000 });
assert.equal(sale.ok, true);
assert.equal(sale.disposal.netBookValue, 4000);
assert.equal(sale.disposal.gainLoss, 2000);
assert.equal(sale.disposal.result, "plus_value");
const loss = buildAssetDisposal({ ...asset, amortized: 2000 }, { date: "2026-11-25", type: "cession", proceeds: 3000 });
assert.equal(loss.disposal.netBookValue, 10000);
assert.equal(loss.disposal.gainLoss, -7000);
assert.equal(loss.disposal.result, "moins_value");
const scrap = buildAssetDisposal(asset, { date: "2026-11-25", type: "mise_rebut", proceeds: 0 });
assert.equal(scrap.ok, true);
assert.equal(scrap.disposal.result, "moins_value");
assert.equal(validateAssetDisposal({ ...asset, disposedAt: "2026-11-01" }, { date: "2026-11-25", type: "cession", proceeds: 10 }).ok, false);
assert.equal(validateAssetDisposal(asset, { date: "2026-02-30", type: "cession", proceeds: 10 }).ok, false);
assert.equal(validateAssetDisposal(asset, { date: "2021-12-31", type: "cession", proceeds: 10 }).ok, false);
assert.equal(validateAssetDisposal(asset, { date: "2026-11-25", type: "cession", proceeds: 0 }).ok, false);
const summary = summarizeAssetDisposals([sale.disposal, loss.disposal]);
assert.equal(summary.count, 2);
assert.equal(summary.proceeds, 9000);
assert.equal(summary.gains, 2000);
assert.equal(summary.losses, 7000);
console.log("✓ Lot 19 — sorties et cessions d'immobilisations");
